-- DB-managed role permissions (replaces hardcoded ROLE_PERMISSIONS in shared/index.ts)
CREATE TABLE IF NOT EXISTS "role_permissions" (
  "id"          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "role"        text NOT NULL,
  "permission"  text NOT NULL,
  "granted"     boolean NOT NULL DEFAULT true,
  "updated_by"  uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "updated_at"  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "role_permissions_role_perm_uq" UNIQUE ("role", "permission")
);

CREATE INDEX IF NOT EXISTS "role_permissions_role_idx" ON "role_permissions"("role");

